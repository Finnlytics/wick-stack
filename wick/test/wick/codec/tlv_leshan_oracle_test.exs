defmodule Wick.Codec.TlvLeshanOracleTest do
  @moduledoc """
  Cross-implementation byte-equality test against Eclipse Leshan 2.0.0-M18.

  For each `test/fixtures/tlv/*.json` fixture, this test:

  1. Loads the JSON spec — a request path, an Object ID, and a list of Resources with their
     declared LwM2M types.
  2. Builds an equivalent `Wick.Object.Registry` and `Wick.Senml.Pack` from that spec.
  3. Encodes via `Wick.Codec.Tlv.encode/2`.
  4. Compares the bytes to the sibling `.bin`, produced by Leshan's `DefaultLwM2mEncoder`
     (generated by `tools/leshan_oracle/`, mode `tlv`).

  Both implementations are handed the *same* declared model, which is the only way this
  comparison means anything: TLV values are bare bytes, so two implementations working from
  different models can agree byte-for-byte on the wrong thing.

  Decoding is checked too — the fixture bytes must come back as the values that went in.
  That is a stronger statement than encoder agreement alone, because a symmetric mistake in
  Wick's own encode/decode pair would still pass a round-trip test.

  The Leshan-produced `.bin` files are committed and this test reads them directly. **No JVM
  is required to run the test.** See `tools/leshan_oracle/README.md`.
  """

  use ExUnit.Case, async: true
  @moduletag :oracle

  alias Wick.Codec.Tlv
  alias Wick.Object.Definition
  alias Wick.Object.Registry
  alias Wick.Object.Resource
  alias Wick.Senml.Pack
  alias Wick.Senml.Record

  @fixtures_dir Path.join(__DIR__, "../../fixtures/tlv") |> Path.expand()

  for json_path <-
        @fixtures_dir
        |> File.ls!()
        |> Enum.filter(&String.ends_with?(&1, ".json"))
        |> Enum.sort()
        |> Enum.map(&Path.join(@fixtures_dir, &1)) do
    @json_path json_path
    @stem json_path |> Path.basename() |> Path.rootname(".json")
    @leshan_bin Path.join(@fixtures_dir, "#{@stem}.bin")

    test "#{@stem}: Wick encoder output matches Leshan's bytes" do
      spec = @json_path |> File.read!() |> Jason.decode!()
      expected = File.read!(@leshan_bin)

      assert {:ok, encoded} = Tlv.encode(build_pack(spec), opts(spec))

      assert IO.iodata_to_binary(encoded) == expected, """
      Encoder output did not match #{Path.basename(@leshan_bin)}.
      Expected (#{byte_size(expected)} bytes): #{Base.encode16(expected)}
      Got      (#{IO.iodata_length(encoded)} bytes): #{Base.encode16(IO.iodata_to_binary(encoded))}
      """
    end

    test "#{@stem}: Wick decodes Leshan's bytes back to the fixture's values" do
      spec = @json_path |> File.read!() |> Jason.decode!()

      assert {:ok, pack} = Tlv.decode(File.read!(@leshan_bin), opts(spec))

      assert normalise(pack) == normalise(build_pack(spec))
    end
  end

  test "every .bin fixture has a sibling .json input (no orphans)" do
    bins =
      @fixtures_dir |> File.ls!() |> Enum.filter(&String.ends_with?(&1, ".bin")) |> MapSet.new()

    expected =
      @fixtures_dir
      |> File.ls!()
      |> Enum.filter(&String.ends_with?(&1, ".json"))
      |> Enum.map(&String.replace_suffix(&1, ".json", ".bin"))
      |> MapSet.new()

    assert MapSet.difference(bins, expected) |> Enum.to_list() == []
  end

  # ── Fixture spec -> Wick ────────────────────────────────────────────────────

  defp opts(spec) do
    {:ok, path} = Wick.Path.parse(spec["path"])
    [path: path, model: build_model(spec)]
  end

  defp build_model(spec) do
    resources =
      Enum.map(spec["resources"], fn resource ->
        %Resource{
          resource_id: resource["id"],
          name: "Resource #{resource["id"]}",
          type: type(resource["type"]),
          operations: [:read, :write],
          multiple_instances: if(resource["instances"], do: :multiple, else: :single),
          mandatory: :optional
        }
      end)

    Registry.from_definitions([
      %Definition{
        object_id: spec["object_id"],
        name: "Object #{spec["object_id"]}",
        multiple_instances: :multiple,
        mandatory: :optional,
        resources: resources
      }
    ])
  end

  defp build_pack(spec) do
    {:ok, path} = Wick.Path.parse(spec["path"])
    instance_id = path.object_instance_id || 0
    object_id = spec["object_id"]

    spec["resources"]
    |> Enum.flat_map(fn resource ->
      base = "/#{object_id}/#{instance_id}/#{resource["id"]}"
      type = type(resource["type"])

      case resource["instances"] do
        nil ->
          [record(base, type, resource["value"])]

        instances ->
          instances
          |> Enum.sort_by(fn {key, _value} -> String.to_integer(key) end)
          |> Enum.map(fn {key, value} -> record("#{base}/#{key}", type, value) end)
      end
    end)
    |> Pack.new()
  end

  defp record(name, type, value) when type in [:string, :core_link],
    do: %Record{name: name, string_value: value}

  defp record(name, :opaque, value),
    do: %Record{name: name, opaque_value: Base.decode16!(value, case: :mixed)}

  defp record(name, :boolean, value), do: %Record{name: name, boolean_value: value}
  defp record(name, :objlnk, value), do: %Record{name: name, object_link_value: value}
  defp record(name, :float, value), do: %Record{name: name, number_value: value * 1.0}
  defp record(name, _numeric, value), do: %Record{name: name, number_value: value}

  defp type("STRING"), do: :string
  defp type("INTEGER"), do: :integer
  defp type("UNSIGNED_INTEGER"), do: :unsigned_integer
  defp type("FLOAT"), do: :float
  defp type("BOOLEAN"), do: :boolean
  defp type("OPAQUE"), do: :opaque
  defp type("TIME"), do: :time
  defp type("OBJLNK"), do: :objlnk
  defp type("CORELINK"), do: :core_link

  # Compare on name and value only. Record ordering is an encoder concern already covered by
  # the byte comparison, and the base-name fields are not part of what TLV carries.
  defp normalise(%Pack{records: records}) do
    records
    |> Enum.map(&{&1.name, Record.value(&1)})
    |> Enum.sort()
  end
end
