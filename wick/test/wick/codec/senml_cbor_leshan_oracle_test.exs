defmodule Wick.Codec.SenmlCborLeshanOracleTest do
  @moduledoc """
  Cross-implementation byte-equality test against Eclipse Leshan 2.0.0-M18.

  For each `test/fixtures/senml_cbor/*.json` fixture, this test:

  1. Loads the JSON spec.
  2. Builds the equivalent `Wick.Senml.Pack`.
  3. Encodes via `Wick.Codec.SenmlCbor.encode/2`.
  4. Compares the encoded bytes to the sibling `.bin` (Leshan's output, generated by
     `tools/leshan_oracle/`). If a sibling `.wick.bin` exists, that takes precedence —
     it documents a deliberate, ADR-tracked divergence from Leshan (see ADR 0003).

  The Leshan-produced `.bin` files are committed and the test reads them directly. **No
  JVM is required to run the test.** The Java oracle is run by hand only when the fixture
  corpus changes — see `tools/leshan_oracle/README.md`.
  """

  use ExUnit.Case, async: true
  @moduletag :oracle

  alias Wick.Codec.SenmlCbor
  alias Wick.Senml.Pack
  alias Wick.Senml.Record

  @fixtures_dir Path.join(__DIR__, "../../fixtures/senml_cbor") |> Path.expand()

  for json_path <-
        @fixtures_dir
        |> File.ls!()
        |> Enum.filter(&String.ends_with?(&1, ".json"))
        |> Enum.sort()
        |> Enum.map(&Path.join(@fixtures_dir, &1)) do
    @json_path json_path
    @stem json_path |> Path.basename() |> Path.rootname(".json")
    @leshan_bin Path.join(@fixtures_dir, "#{@stem}.bin")
    @wick_bin Path.join(@fixtures_dir, "#{@stem}.wick.bin")

    test "#{@stem}: Wick encoder output matches the committed reference bytes" do
      spec = @json_path |> File.read!() |> Jason.decode!()
      pack = build_pack(spec)
      opts = if Map.get(spec, "allow_no_value", false), do: [allow_no_value: true], else: []

      assert {:ok, encoded} = SenmlCbor.encode(pack, opts)

      expected_path =
        if File.exists?(@wick_bin), do: @wick_bin, else: @leshan_bin

      expected = File.read!(expected_path)

      assert encoded == expected, """
      Encoder output did not match #{Path.basename(expected_path)}.
      Expected (#{byte_size(expected)} bytes): #{Base.encode16(expected)}
      Got      (#{byte_size(encoded)} bytes): #{Base.encode16(encoded)}
      """
    end
  end

  test "every .bin fixture has a sibling .json input (no orphans)" do
    bins =
      @fixtures_dir
      |> File.ls!()
      |> Enum.filter(&String.ends_with?(&1, ".bin"))
      |> Enum.reject(&String.ends_with?(&1, ".wick.bin"))
      |> Enum.map(&Path.rootname(&1, ".bin"))
      |> MapSet.new()

    jsons =
      @fixtures_dir
      |> File.ls!()
      |> Enum.filter(&String.ends_with?(&1, ".json"))
      |> Enum.map(&Path.rootname(&1, ".json"))
      |> MapSet.new()

    assert MapSet.difference(bins, jsons) == MapSet.new(),
           "found .bin files without a matching .json"
  end

  test "every .wick.bin override has a sibling .bin (overrides require a Leshan baseline)" do
    overrides =
      @fixtures_dir
      |> File.ls!()
      |> Enum.filter(&String.ends_with?(&1, ".wick.bin"))
      |> Enum.map(&Path.rootname(&1, ".wick.bin"))

    for stem <- overrides do
      leshan_bin = Path.join(@fixtures_dir, "#{stem}.bin")

      assert File.exists?(leshan_bin),
             "fixture #{stem} has a .wick.bin override but no Leshan .bin — divergence " <>
               "should be visible against a Leshan baseline (see ADR 0003)"
    end
  end

  defp build_pack(%{"records" => records}) do
    Pack.new(Enum.map(records, &build_record/1))
  end

  defp build_record(map) do
    %Record{
      base_name: map["base_name"],
      base_time: number_or_nil(map["base_time"]),
      name: map["name"],
      time: number_or_nil(map["time"]),
      number_value: number_or_nil(map["number_value"]),
      string_value: map["string_value"],
      boolean_value: map["boolean_value"],
      opaque_value: opaque_or_nil(map["opaque_value"]),
      object_link_value: map["object_link_value"]
    }
  end

  defp number_or_nil(nil), do: nil
  defp number_or_nil(n) when is_integer(n) or is_float(n), do: n

  defp opaque_or_nil(nil), do: nil
  defp opaque_or_nil(hex) when is_binary(hex), do: Base.decode16!(hex, case: :mixed)
end
